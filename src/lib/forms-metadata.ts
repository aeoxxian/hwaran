/**
 * 양식별 구조화 메타데이터.
 *
 * `forms-catalog.ts` 의 각 양식 ID 에 대응하는 작성 목적·필드·제출/검토 주체 정보를 정리한다.
 * Worker N 의 제출 UI 가 사용자에게 어떤 항목을 채워야 하는지 안내하기 위해 사용한다.
 *
 * 원본 docx/xlsx 파일에서 추출한 라벨을 기반으로 정리했으며,
 * 제출/검토 주체는 양식 본문(예: 수신처, 결재란, "동아리연합회 귀중" 등)을 단서로 추정했다.
 */

export interface FormMetadata {
  /** forms-catalog.ts 의 FormTemplate.id 와 동일 */
  id: string;
  /** 이 양식이 어떤 용도인지 1~2문장 요약 (한국어) */
  purpose: string;
  /** 양식에 포함된 주요 입력 항목/라벨 */
  fields: string[];
  /** 작성·제출 주체 (예: 동아리장 / 후보자 / 모든회원 / 본부원 지원자 등) */
  submitter: string;
  /** 검토·승인 주체 (예: 회장단 / 국장팀장 / 국원 / 본부 / 중앙선거관리위원회 등) */
  reviewer: string;
  /** 표·서명란·첨부 등 구조적으로 특이한 점 */
  notes?: string;
}

